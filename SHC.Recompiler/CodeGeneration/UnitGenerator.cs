using System.Text;
using SHC.Recompiler.Analysis;

namespace SHC.Recompiler.CodeGeneration;

/// <summary>Resultado da geração do projeto de uma unidade.</summary>
/// <param name="ProjectDirectory">Pasta do projeto gerado.</param>
/// <param name="FunctionCount">Quantidade de funções geradas.</param>
/// <param name="FileCount">Quantidade de arquivos .cs gerados.</param>
/// <param name="TotalBytes">Tamanho total do código gerado.</param>
public sealed record GenerationResult(
    string ProjectDirectory,
    int FunctionCount,
    int FileCount,
    long TotalBytes);

/// <summary>
/// Gera um projeto C# com todas as funções de uma unidade (executável
/// principal ou overlay), dividido em vários arquivos.
/// </summary>
public static class UnitGenerator
{
    // Tamanho aproximado, em caracteres, a partir do qual um novo arquivo é iniciado.
    private const int MaxFileLength = 1_500_000;

    private static readonly UTF8Encoding Utf8NoBom = new(false);

    /// <summary>
    /// Gera o projeto em "&lt;solutionDirectory&gt;\Generated\SHC.Generated.&lt;Nome&gt;".
    /// O projeto referencia o SHC.Runtime da solução.
    /// </summary>
    public static GenerationResult Generate(
        AnalysisResult analysis,
        string solutionDirectory,
        EmitOptions options)
    {
        ArgumentNullException.ThrowIfNull(analysis);
        ArgumentException.ThrowIfNullOrWhiteSpace(solutionDirectory);
        ArgumentNullException.ThrowIfNull(options);

        string name = GetUnitName(analysis.Unit);
        string projectName = $"SHC.Generated.{name}";
        string className = $"{name}Unit";
        string @namespace = projectName;

        string projectDirectory = Path.Combine(
            solutionDirectory,
            "Generated",
            projectName);

        Directory.CreateDirectory(projectDirectory);

        // Remove arquivos de uma geração anterior para não sobrar código antigo.
        foreach (string old in Directory.GetFiles(projectDirectory, "Functions_*.cs"))
        {
            File.Delete(old);
        }

        string header =
            "// <auto-generated>\n" +
            "// Gerado por SHC.Recompiler. Não edite este arquivo.\n" +
            "// </auto-generated>\n" +
            "using SHC.Runtime.Cpu;\n" +
            "using SHC.Runtime.Machine;\n" +
            "using static SHC.Runtime.Cpu.Ops;\n" +
            "\n" +
            $"namespace {@namespace};\n" +
            "\n" +
            $"public static partial class {className}\n" +
            "{\n";

        const string footer = "}\n";

        long totalBytes = 0;
        int fileCount = 0;
        var body = new StringBuilder();

        void Flush()
        {
            if (body.Length == 0)
            {
                return;
            }

            fileCount++;

            string text = header + body + footer;
            string path = Path.Combine(projectDirectory, $"Functions_{fileCount:D4}.cs");

            File.WriteAllText(path, text, Utf8NoBom);

            totalBytes += Utf8NoBom.GetByteCount(text);
            body.Clear();
        }

        // As funções já vêm em ordem crescente de endereço.
        foreach (FunctionInfo function in analysis.Functions.Values)
        {
            body.AppendLine(CSharpFunctionEmitter.Emit(analysis, function, options));

            if (body.Length >= MaxFileLength)
            {
                Flush();
            }
        }

        Flush();

        totalBytes += WriteRegistry(projectDirectory, analysis, @namespace, className);
        totalBytes += WriteProject(projectDirectory, projectName);

        return new GenerationResult(
            projectDirectory,
            analysis.Functions.Count,
            fileCount + 2,
            totalBytes);
    }

    /// <summary>
    /// Nome curto da unidade: "Main" para o executável e o nome do arquivo,
    /// em formato Pascal, para os overlays (FIELD.BIN vira "Field").
    /// </summary>
    public static string GetUnitName(RecompilationUnit unit)
    {
        if (unit.EntryPoint is not null)
        {
            return "Main";
        }

        string name = Path.GetFileNameWithoutExtension(unit.Name).ToLowerInvariant();

        return char.ToUpperInvariant(name[0]) + name[1..];
    }

    // Registra todas as funções no contexto, para chamadas indiretas.
    private static long WriteRegistry(
        string projectDirectory,
        AnalysisResult analysis,
        string @namespace,
        string className)
    {
        var text = new StringBuilder();

        text.AppendLine("// <auto-generated>");
        text.AppendLine("// Gerado por SHC.Recompiler. Não edite este arquivo.");
        text.AppendLine("// </auto-generated>");
        text.AppendLine("using SHC.Runtime.Cpu;");
        text.AppendLine();
        text.AppendLine($"namespace {@namespace};");
        text.AppendLine();
        text.AppendLine($"public static partial class {className}");
        text.AppendLine("{");
        text.AppendLine("    /// <summary>Registra todas as funções desta unidade no contexto.</summary>");
        text.AppendLine("    public static void Register(R5900Context ctx)");
        text.AppendLine("    {");

        foreach (uint entry in analysis.Functions.Keys)
        {
            text.AppendLine(
                $"        ctx.RegisterFunction(0x{entry:X8}u, " +
                $"{CSharpFunctionEmitter.MethodName(entry)});");
        }

        text.AppendLine("    }");
        text.AppendLine("}");

        string content = text.ToString();

        File.WriteAllText(
            Path.Combine(projectDirectory, "Registry.cs"),
            content,
            Utf8NoBom);

        return Utf8NoBom.GetByteCount(content);
    }

    private static long WriteProject(string projectDirectory, string projectName)
    {
        string content =
            "<Project Sdk=\"Microsoft.NET.Sdk\">\n" +
            "\n" +
            "  <ItemGroup>\n" +
            "    <ProjectReference Include=\"..\\..\\SHC.Runtime\\SHC.Runtime.csproj\" />\n" +
            "  </ItemGroup>\n" +
            "\n" +
            "  <PropertyGroup>\n" +
            "    <TargetFramework>net10.0</TargetFramework>\n" +
            "    <ImplicitUsings>enable</ImplicitUsings>\n" +
            "    <Nullable>disable</Nullable>\n" +
            "    <!-- Código gerado: avisos de código inalcançável ou variável sem uso não interessam. -->\n" +
            "    <NoWarn>$(NoWarn);CS0162;CS0164;CS0168;CS0219</NoWarn>\n" +
            "  </PropertyGroup>\n" +
            "\n" +
            "</Project>\n";

        File.WriteAllText(
            Path.Combine(projectDirectory, $"{projectName}.csproj"),
            content,
            Utf8NoBom);

        return Utf8NoBom.GetByteCount(content);
    }
}
